CREATE TABLE IF NOT EXISTS catalogue (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  body TEXT NOT NULL,
  revision INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS catalogue_history (
  revision INTEGER PRIMARY KEY,
  body TEXT NOT NULL,
  saved_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TRIGGER IF NOT EXISTS catalogue_backup BEFORE UPDATE ON catalogue
BEGIN
  INSERT OR REPLACE INTO catalogue_history (revision, body) VALUES (OLD.revision, OLD.body);
  DELETE FROM catalogue_history WHERE revision NOT IN (SELECT revision FROM catalogue_history ORDER BY revision DESC LIMIT 10);
END;
CREATE TABLE IF NOT EXISTS media (
  id TEXT PRIMARY KEY,
  body BLOB NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TRIGGER IF NOT EXISTS media_capacity BEFORE INSERT ON media
WHEN (SELECT COALESCE(SUM(length(body)),0) FROM media) + length(NEW.body) > 100000000
BEGIN SELECT RAISE(ABORT, 'PHOTO_STORAGE_FULL'); END;
CREATE TABLE IF NOT EXISTS login_attempts (
  id TEXT PRIMARY KEY,
  attempts INTEGER NOT NULL,
  expires INTEGER NOT NULL
);
